"""Install Claude Code skill + slash commands into a ``.claude`` directory.

``scripthut agent install`` writes two managed files:

- ``.claude/skills/scripthut/SKILL.md`` — the command and execution-boundary
  briefing. ``scripthut agent prompt`` adds the configured inventory.
- ``.claude/commands/scripthut/debug.md`` — a ``/scripthut:debug [run-id]``
  slash command that walks the failure-diagnosis flow (statuses → stderr →
  classification → proposed fix).

Ownership is tracked with a marker comment so re-install never clobbers a
file the user hand-authored: files carrying the marker are ours to
overwrite; files without it are skipped unless ``force`` is set.
"""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path

from scripthut import __version__

# Substring that marks a file as scripthut-managed. Kept version-free so
# ownership detection survives upgrades; the rendered line appends the
# current version for humans reading the file.
MANAGED_MARKER = "generated by `scripthut agent install`"

SKILL_RELPATH = Path("skills/scripthut/SKILL.md")
DEBUG_COMMAND_RELPATH = Path("commands/scripthut/debug.md")


def _marker_line() -> str:
    return (
        f"<!-- {MANAGED_MARKER} (scripthut v{__version__}) — "
        "re-run it to update; hand edits will be overwritten -->"
    )


def render_skill() -> str:
    """Agent guidance for the retained CLI."""
    return f"""---
name: scripthut
description: >-
  Deliver git sources, launch ScriptFlow controllers on Slurm and observe runs, logs,
  and cancellation with ScriptHut. Use for ScriptFlow or Slurm/PBS backend
  status; not for scheduling individual tasks or installing environments.
---

{_marker_line()}

# ScriptHut Agent Brief

Read `scripthut agent prompt` for configured backend and source names.
Use `scripthut status` and `scripthut backend list --json` to check connectivity.
Use `scripthut source list --json`, `source view NAME`, and `source sync NAME`
for configured repository metadata and synchronization.

## ScriptFlow

Commands use local configuration and the SSH command transport:

- `scripthut scriptflow register --backend NAME --run-dir /data/project/.sf/runs/ID --json`
- `scripthut scriptflow list --json`
- `scripthut scriptflow view REFERENCE --json`
- `scripthut scriptflow logs REFERENCE TASK --tail 200`
- `scripthut scriptflow launch --backend NAME --workdir /data/project --flow FLOW --run-id ID --json`
- `scripthut scriptflow launch --source SOURCE --backend NAME --flow FLOW --run-id ID --json`
- `scripthut scriptflow flows --source SOURCE --json`
- `scripthut scriptflow images --source SOURCE --backend NAME --json`
- `scripthut scriptflow discover --source SOURCE --backend NAME --register`
- `scripthut scriptflow discover --backend NAME --workdir /data/project --register`
- `scripthut scriptflow cancel REFERENCE --wait --json`
- `scripthut scriptflow cleanup REFERENCE`
- `scripthut scriptflow release REFERENCE`
- `scripthut scriptflow unregister REFERENCE`

Configure `scriptflow.env_group` and a named backend `env_groups` entry before
launching. Resource overrides and `--force-pattern PATTERN` apply to launch.
Repeat the same launch to reconcile its durable request; never blindly resubmit
an ambiguous request. ScriptFlow owns all task execution and retry decisions.

Source launches use a fixed checkout, default `<clone_dir>/.worktrees/source-<name>`.
Configure absolute `workdir` and relative `flow_dir` to change it. Use `--branch`
or `--commit` to pin code; `--snapshot` selects the per-commit checkout. Source and
explicit workdir are mutually exclusive. Backend may be omitted with one configured
backend. Refuse dirty tracked files, live/stale runs, unknown run records and
non-fast-forward updates; never reset, stash or clean a cluster checkout. Untracked
outputs stay. `flows` reads committed text, using local_path or a backend
copy. New commits need new explicit run IDs; identical requests never move code again.

Source images require digest-pinned `ref` or a committed `ref_file`; `allow_tag`
is an explicit opt-out. `images` only checks presence. Missing images are pulled
inside the controller compute job, never on the login node. The flow reads
`SCRIPTHUT_IMAGE_<NAME>`; manual users source `.sf/images.sh` after preparation.
Registry credentials come from the backend's local token file, never from command
arguments. The controller consumes and deletes its token file before activation.
Pulls use node-local scratch and `image_pull_timeout_seconds` (default 600).
Use `view` for elapsed time and redacted progress; an ended controller during
preparation is a launch problem. Do not print tokens or delete image files. A failed image preparation
is a launch problem with workflow `not started`; use a new run ID after fixing it.
Binds belong to the flow and runtime activation belongs to the environment group.

Fetch declared outputs with `scriptflow fetch REFERENCE --to LOCAL_DIR`.
Use repeatable `--task NAME_OR_ID` or `--path PATH`, not both; `--strip PREFIX`
removes a relative staging prefix. Inspect `--dry-run --json` before copying.
Files already at the destination require `--overwrite`. Fetch stays inside the source checkout
(or launch/record workdir), rejects escaping symlinks, verifies size/SHA-256 and
never writes remotely. Missing/skipped files yield exit 1 while other files proceed.
Raise `settings.fetch_max_file_bytes` / `fetch_max_total_bytes` for larger outputs
(default 1 GiB/file, 10 GiB total). No fetch API or web action exists.

Keep workflow state, controller state and observation freshness separate.
Stale, unreachable, malformed and unsupported-version are observation problems,
not outcomes. Logs accept a task ID or unique name; IDs win. Use `--verbose`
for transport detail. `list` exits 0 when listing succeeds even if a reference
is unreachable; `view` and `logs` exit nonzero for unreadable records.

Cancel writes the cancellation request; completion requires terminal workflow
state and cleanup_pending false. Cleanup is explicit and runs in a compute job
only after the controller has ended. Release cancels only the owned controller;
terminal workflow and finished cleanup are required unless force is explicit.
Controller expiry leaves task jobs running. Unregister removes only local state.

## Server

Run `scripthut --config scripthut.yaml`, or use `scripthut daemon start`, `status`,
`logs`, and `stop`. Open `/` for the overview, `/runs` (also `/scriptflow`) for
runs, `/backends` for read-only job listing, and `/terminals` to attach to a tmux session. The versioned
ScriptFlow API offers list/view, refresh, bounded attempt logs and non-waiting
cancel; there is no cleanup or release endpoint. Viewing or
refreshing never changes remote execution. Do not log into hosts directly or
issue scheduler task submission/cancellation commands.

The Sources page launches controllers through the CLI handler, retaining the form's
run ID for retries. `/disk` displays cached sizes only, with no delete/cleanup action.
Page rendering and passive SSE use local cached records.
"""


def render_debug_command() -> str:
    """Diagnose an observed ScriptFlow run."""
    return f"""---
description: Diagnose ScriptFlow state and attempt logs without changing execution
argument-hint: [reference-id]
---

{_marker_line()}

Inspect `$ARGUMENTS` with `scripthut scriptflow view REFERENCE --json`.
If no reference was given, use `scripthut scriptflow list --json`.
Read failed attempts with `scripthut scriptflow logs REFERENCE TASK --tail 200`.
Report workflow outcome separately from observation and controller state.
Name the relevant code or resource error. Propose a fix; launch or request
cancellation only when asked. Never submit or cancel individual task jobs.
"""


@dataclass
class InstallResult:
    """Outcome of installing one managed file."""

    path: Path
    action: str  # created | updated | unchanged | skipped


def _install_one(path: Path, content: str, force: bool) -> InstallResult:
    if path.exists():
        existing = path.read_text(encoding="utf-8")
        if existing == content:
            return InstallResult(path, "unchanged")
        if MANAGED_MARKER not in existing and not force:
            return InstallResult(path, "skipped")
        action = "updated"
    else:
        action = "created"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")
    return InstallResult(path, action)


def install_assets(claude_dir: Path, force: bool = False) -> list[InstallResult]:
    """Write the skill and slash-command files under ``claude_dir``.

    ``claude_dir`` is the ``.claude`` directory itself (project-level
    ``<repo>/.claude`` or user-level ``~/.claude``).
    """
    return [
        _install_one(claude_dir / SKILL_RELPATH, render_skill(), force),
        _install_one(claude_dir / DEBUG_COMMAND_RELPATH, render_debug_command(), force),
    ]
